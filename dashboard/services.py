"""Canonical service metadata for the dashboard console and its workbenches."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field as dataclass_field
from typing import Literal

from .actions import ServiceAction, action, field as action_field

ServiceMaturity = Literal[
    'missing',
    'inventory_only',
    'read_only_inspector',
    'interactive_workbench',
    'tutorial_ready',
]


@dataclass(frozen=True)
class ServiceDefinition:
    key: str
    title: str
    eyebrow: str
    category: str
    maturity: ServiceMaturity = 'inventory_only'
    api_path: str | None = None
    docs_url: str = ''
    tags: tuple[str, ...] = dataclass_field(default_factory=tuple)
    actions: tuple[ServiceAction, ...] = dataclass_field(default_factory=tuple)

    def as_dict(self) -> dict:
        data = asdict(self)
        data['api_path'] = self.api_path or f'/api/{self.key}/'
        data['tags'] = list(self.tags)
        return data


def service(
    key: str,
    title: str,
    eyebrow: str,
    category: str,
    *,
    maturity: ServiceMaturity = 'inventory_only',
    api_path: str | None = None,
    docs_url: str = '',
    tags: tuple[str, ...] = (),
    actions: tuple[ServiceAction, ...] = (),
) -> ServiceDefinition:
    return ServiceDefinition(
        key=key,
        title=title,
        eyebrow=eyebrow,
        category=category,
        maturity=maturity,
        api_path=api_path,
        docs_url=docs_url,
        tags=tags,
        actions=actions,
    )


