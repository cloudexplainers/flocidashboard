def _tags(clf: str = '', saa: str = '', dva: str = '', aif: str = '', dop: str = '', soa: str = '',
          dea: str = '') -> list[dict[str, Any]]:
    """Build tags from space-separated task IDs; the first ID per exam is primary."""
    tags = []
    for exam, tasks in ((CLF, clf), (SAA, saa), (DVA, dva), (AIF, aif), (DOP, dop), (SOA, soa), (DEA, dea)):
        for index, task in enumerate(tasks.split()):
            tags.append({'exam': exam, 'task': task, 'primary': index == 0})
    return tags


