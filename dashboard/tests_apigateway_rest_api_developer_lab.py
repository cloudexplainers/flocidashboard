"""API Gateway for developers lab: a Lambda backend tested with a sample event, dev and prod stages with stage variables,
a Lambda TOKEN authorizer, request validation with a MOCK integration, a Cognito authorizer, and an API key with a usage
plan. The fake behaves like Floci 2.3.0: requests run the real handler code, a key works only on stages its usage plan
covers, usage plans read back with only their name, and throttling and quotas are never enforced."""

