def client_error(code: str, message: str = 'refused') -> ClientError:
    return ClientError({'Error': {'Code': code, 'Message': message}, 'ResponseMetadata': {'HTTPStatusCode': 400}}, 'Operation')


class Payload:
    def __init__(self, value):
        self.data = json.dumps(value).encode()

    def read(self):
        return self.data


def load_handler(code: bytes):
    with zipfile.ZipFile(io.BytesIO(code)) as archive:
        name = archive.namelist()[0]
        source = archive.read(name).decode()
    namespace: dict = {}
    exec(compile(source, name, 'exec'), namespace)  # noqa: S102 - code generated by the lab under test
    return namespace['handler']


class FakeAws:
    def __init__(self, keep_plan_settings=False, enforce_quota=False, reject_plan_patch=True):
        self.keep_plan_settings = keep_plan_settings
        self.enforce_quota = enforce_quota
        self.reject_plan_patch = reject_plan_patch
        self.ids = itertools.count(1)
        self.roles: dict[str, dict] = {}
        self.role_policies: dict[tuple[str, str], str] = {}
        self.functions: dict[str, dict] = {}
        self.apis: dict[str, dict] = {}
        self.pools: dict[str, dict] = {}
        self.keys: dict[str, dict] = {}
        self.plans: dict[str, dict] = {}
        self.tokens: dict[str, dict] = {}

    def _id(self, prefix='id'):
        return f'{prefix}{next(self.ids):04d}'

    # IAM
    def get_role(self, RoleName):
        if RoleName not in self.roles:
            raise client_error('NoSuchEntity')
        return {'Role': self.roles[RoleName]}

    def create_role(self, RoleName, AssumeRolePolicyDocument, Description=''):
        self.roles[RoleName] = {'RoleName': RoleName, 'Arn': f'arn:aws:iam::000000000000:role/{RoleName}'}

    def put_role_policy(self, RoleName, PolicyName, PolicyDocument):
        self.role_policies[(RoleName, PolicyName)] = PolicyDocument

    def delete_role_policy(self, RoleName, PolicyName):
        if self.role_policies.pop((RoleName, PolicyName), None) is None:
            raise client_error('NoSuchEntity')

    def delete_role(self, RoleName):
        if self.roles.pop(RoleName, None) is None:
            raise client_error('NoSuchEntity')

    # Lambda
    def get_function(self, FunctionName):
        if FunctionName not in self.functions:
            raise client_error('ResourceNotFoundException')
        return {'Configuration': self.functions[FunctionName]['config']}

    def create_function(self, FunctionName, Runtime, Handler, Role, Timeout, Code, Description, Tags):
        self.functions[FunctionName] = {'config': {'FunctionName': FunctionName, 'Runtime': Runtime, 'Role': Role,
                                                   'Handler': Handler, 'State': 'Active'},
                                        'code': Code['ZipFile'], 'permissions': {}}

    def update_function_code(self, FunctionName, ZipFile):
        self.functions[FunctionName]['code'] = ZipFile

    def invoke(self, FunctionName, Payload: bytes):
        handler = load_handler(self.functions[FunctionName]['code'])
        return {'Payload': globals()['Payload'](handler(json.loads(Payload), None))}

    def remove_permission(self, FunctionName, StatementId):
        if self.functions[FunctionName]['permissions'].pop(StatementId, None) is None:
            raise client_error('ResourceNotFoundException')

    def add_permission(self, FunctionName, StatementId, **kwargs):
        self.functions[FunctionName]['permissions'][StatementId] = kwargs

    def delete_function(self, FunctionName):
        if self.functions.pop(FunctionName, None) is None:
            raise client_error('ResourceNotFoundException')

    # API Gateway: APIs, resources, methods
    def get_rest_apis(self, limit):
        return {'items': [{'id': api_id, 'name': api['name']} for api_id, api in self.apis.items()]}

    def create_rest_api(self, name, description, endpointConfiguration, tags):
        api_id = self._id('api')
        root = self._id('res')
        self.apis[api_id] = {'name': name, 'resources': {root: {'id': root, 'path': '/', 'methods': {}}},
                             'authorizers': {}, 'models': {}, 'validators': {}, 'deployments': [], 'stages': {}}
        return {'id': api_id}

    def delete_rest_api(self, restApiId):
        if self.apis.pop(restApiId, None) is None:
            raise client_error('NotFoundException')

    def get_resources(self, restApiId, limit, embed):
        return {'items': list(self.apis[restApiId]['resources'].values())}

    def create_resource(self, restApiId, parentId, pathPart):
        resource_id = self._id('res')
        self.apis[restApiId]['resources'][resource_id] = {'id': resource_id, 'path': f'/{pathPart}', 'methods': {}}
        return {'id': resource_id}

    def _methods(self, api_id, resource_id):
        return self.apis[api_id]['resources'][resource_id]['methods']

    def get_method(self, restApiId, resourceId, httpMethod):
        method = self._methods(restApiId, resourceId).get(httpMethod)
        if method is None:
            raise client_error('NotFoundException')
        return method

    def delete_method(self, restApiId, resourceId, httpMethod):
        self._methods(restApiId, resourceId).pop(httpMethod)

    def put_method(self, restApiId, resourceId, httpMethod, authorizationType, **kwargs):
        self._methods(restApiId, resourceId)[httpMethod] = {'httpMethod': httpMethod,
                                                             'authorizationType': authorizationType,
                                                             'apiKeyRequired': False, **kwargs}

    def update_method(self, restApiId, resourceId, httpMethod, patchOperations):
        method = self._methods(restApiId, resourceId)[httpMethod]
        for op in patchOperations:
            name, value = op['path'].strip('/'), op['value']
            method[name] = value == 'true' if name == 'apiKeyRequired' else value

    def put_integration(self, restApiId, resourceId, httpMethod, type, **kwargs):
        self._methods(restApiId, resourceId)[httpMethod]['methodIntegration'] = {'type': type, **kwargs}

    def put_method_response(self, **kwargs):
        pass

    def put_integration_response(self, restApiId, resourceId, httpMethod, statusCode, responseTemplates):
        integration = self._methods(restApiId, resourceId)[httpMethod]['methodIntegration']
        integration['responseStatus'] = int(statusCode)

    # Authorizers, models, validators
    def get_authorizers(self, restApiId, limit):
        return {'items': list(self.apis[restApiId]['authorizers'].values())}

    def create_authorizer(self, restApiId, name, type, **kwargs):
        authorizer_id = self._id('auth')
        self.apis[restApiId]['authorizers'][authorizer_id] = {'id': authorizer_id, 'name': name, 'type': type, **kwargs}
        return {'id': authorizer_id}

    def update_authorizer(self, restApiId, authorizerId, patchOperations):
        for op in patchOperations:
            self.apis[restApiId]['authorizers'][authorizerId][op['path'].strip('/')] = op['value']

    def get_models(self, restApiId, limit):
        return {'items': [{'name': name} for name in self.apis[restApiId]['models']]}

    def create_model(self, restApiId, name, contentType, schema, description):
        self.apis[restApiId]['models'][name] = json.loads(schema)

    def update_model(self, restApiId, modelName, patchOperations):
        self.apis[restApiId]['models'][modelName] = json.loads(patchOperations[0]['value'])

    def get_request_validators(self, restApiId):
        return {'items': list(self.apis[restApiId]['validators'].values())}

    def create_request_validator(self, restApiId, name, validateRequestBody, validateRequestParameters):
        validator_id = self._id('val')
        self.apis[restApiId]['validators'][validator_id] = {'id': validator_id, 'name': name,
                                                            'validateRequestBody': validateRequestBody}
        return {'id': validator_id}

    # Deployments and stages
    def create_deployment(self, restApiId, description='', stageName=None, variables=None):
        api = self.apis[restApiId]
        deployment_id = self._id('dep')
        api['deployments'].append(deployment_id)
        if stageName:
            stage = api['stages'].setdefault(stageName, {'stageName': stageName, 'variables': {}})
            stage['deploymentId'] = deployment_id
            if variables:
                stage['variables'] = dict(variables)
        return {'id': deployment_id}

    def get_deployments(self, restApiId, limit):
        return {'items': [{'id': item} for item in self.apis[restApiId]['deployments']]}

    def get_stage(self, restApiId, stageName):
        stage = self.apis[restApiId]['stages'].get(stageName)
        if stage is None:
            raise client_error('NotFoundException')
        return dict(stage)

    def create_stage(self, restApiId, stageName, deploymentId, variables, description, tags):
        self.apis[restApiId]['stages'][stageName] = {'stageName': stageName, 'deploymentId': deploymentId,
                                                     'variables': dict(variables)}

    def update_stage(self, restApiId, stageName, patchOperations):
        stage = self.apis[restApiId]['stages'][stageName]
        for op in patchOperations:
            if op['path'] == '/deploymentId':
                stage['deploymentId'] = op['value']
            else:
                stage['variables'][op['path'].split('/')[-1]] = op['value']

    # API keys and usage plans
    def get_api_keys(self, nameQuery, includeValues, limit):
        return {'items': [dict(key) for key in self.keys.values() if key['name'].startswith(nameQuery)]}

    def create_api_key(self, name, enabled, description, tags):
        key_id = self._id('key')
        self.keys[key_id] = {'id': key_id, 'name': name, 'enabled': enabled, 'value': f'secret-{key_id}'}
        return dict(self.keys[key_id])

    def delete_api_key(self, apiKey):
        if self.keys.pop(apiKey, None) is None:
            raise client_error('NotFoundException')

    def _plan_view(self, plan):
        view = {'id': plan['id'], 'name': plan['name'], 'description': plan['description']}
        if self.keep_plan_settings:
            view.update({name: plan[name] for name in ('apiStages', 'throttle', 'quota')})
        return view

    def get_usage_plans(self, limit):
        return {'items': [self._plan_view(plan) for plan in self.plans.values()]}

    def create_usage_plan(self, name, description, apiStages, throttle, quota):
        plan_id = self._id('plan')
        self.plans[plan_id] = {'id': plan_id, 'name': name, 'description': description, 'apiStages': apiStages,
                               'throttle': throttle, 'quota': quota, 'keys': [], 'used': 0}
        return self._plan_view(self.plans[plan_id])

    def update_usage_plan(self, usagePlanId, patchOperations):
        if self.reject_plan_patch:
            raise client_error('BadRequestException', f'Unsupported path: {patchOperations[0]["path"]}')

    def delete_usage_plan(self, usagePlanId):
        if self.plans.pop(usagePlanId, None) is None:
            raise client_error('NotFoundException')

    def get_usage_plan_keys(self, usagePlanId, limit):
        return {'items': [{'id': key_id} for key_id in self.plans[usagePlanId]['keys']]}

    def create_usage_plan_key(self, usagePlanId, keyId, keyType):
        self.plans[usagePlanId]['keys'].append(keyId)

    def delete_usage_plan_key(self, usagePlanId, keyId):
        self.plans[usagePlanId]['keys'].remove(keyId)

    # Cognito
    def list_user_pools(self, MaxResults):
        return {'UserPools': [{'Id': pool_id, 'Name': pool['Name']} for pool_id, pool in self.pools.items()]}

    def describe_user_pool(self, UserPoolId):
        pool = self.pools[UserPoolId]
        return {'UserPool': {'Id': UserPoolId, 'Name': pool['Name'], 'Arn': f'arn:aws:cognito-idp:us-east-1:000000000000:userpool/{UserPoolId}'}}

    def create_user_pool(self, PoolName, **kwargs):
        pool_id = f'us-east-1_{self._id("pool")}'
        self.pools[pool_id] = {'Name': PoolName, 'clients': [], 'users': {}}

    def list_user_pool_clients(self, UserPoolId, MaxResults):
        return {'UserPoolClients': list(self.pools[UserPoolId]['clients'])}

    def create_user_pool_client(self, UserPoolId, ClientName, **kwargs):
        client = {'ClientId': self._id('client'), 'ClientName': ClientName, 'pool': UserPoolId}
        self.pools[UserPoolId]['clients'].append(client)
        return {'UserPoolClient': client}

    def admin_create_user(self, UserPoolId, Username, UserAttributes, **kwargs):
        users = self.pools[UserPoolId]['users']
        if Username in users:
            raise client_error('UsernameExistsException')
        attributes = {item['Name']: item['Value'] for item in UserAttributes}
        users[Username] = {'sub': self._id('sub'), **attributes}

    def admin_set_user_password(self, UserPoolId, Username, Password, Permanent):
        self.pools[UserPoolId]['users'][Username]['password'] = Password

    def admin_get_user(self, UserPoolId, Username):
        user = self.pools[UserPoolId]['users'][Username]
        return {'UserAttributes': [{'Name': name, 'Value': user[name]} for name in ('sub', 'email')]}

    def initiate_auth(self, ClientId, AuthFlow, AuthParameters):
        pool_id = next(pool_id for pool_id, pool in self.pools.items()
                       if any(client['ClientId'] == ClientId for client in pool['clients']))
        user = self.pools[pool_id]['users'][AuthParameters['USERNAME']]
        if user.get('password') != AuthParameters['PASSWORD']:
            raise client_error('NotAuthorizedException')
        token = f'eyJ.id-token.{self._id("tok")}'
        self.tokens[token] = {'pool': pool_id, **user}
        return {'AuthenticationResult': {'IdToken': token}}

    def delete_user_pool(self, UserPoolId):
        if self.pools.pop(UserPoolId, None) is None:
            raise client_error('ResourceNotFoundException')

    # Requests to a stage, served from the latest configuration as Floci does
    def call(self, api_id, stage, path, method='GET', headers=None, body=None):
        headers = headers or {}
        api = self.apis.get(api_id)
        if not api or stage not in api['stages']:
            return {'Status': 403, 'Body': {'message': 'Forbidden'}}
        resource = next((item for item in api['resources'].values() if item['path'] == f'/{path}'), None)
        config = (resource or {}).get('methods', {}).get(method)
        if not config:
            return {'Status': 403, 'Body': {'message': 'Missing Authentication Token'}}
        if config.get('apiKeyRequired'):
            key = next((item for item in self.keys.values() if item['value'] == headers.get('x-api-key')), None)
            plan = next((item for item in self.plans.values() if key and key['id'] in item['keys']
                         and {'apiId': api_id, 'stage': stage} in item['apiStages']), None)
            if not plan:
                return {'Status': 403, 'Body': {'message': 'Forbidden'}}
            plan['used'] += 1
            if self.enforce_quota and plan['used'] > plan['quota']['limit']:
                return {'Status': 429, 'Body': {'message': 'Limit Exceeded'}}
        context = {}
        if config['authorizationType'] == 'CUSTOM':
            authorizer = api['authorizers'][config['authorizerId']]
            function = authorizer['authorizerUri'].split('functions/')[1].split('/')[0].split(':')[-1]
            token = headers.get('Authorization')
            if not token:
                return {'Status': 401, 'Body': {'message': 'Unauthorized'}}
            try:
                policy = load_handler(self.functions[function]['code'])(
                    {'type': 'TOKEN', 'authorizationToken': token,
                     'methodArn': f'arn:aws:execute-api:us-east-1:000000000000:{api_id}/{stage}/{method}/{path}'}, None)
            except Exception:  # noqa: BLE001 - the authorizer raises Unauthorized
                return {'Status': 401, 'Body': {'message': 'Unauthorized'}}
            if policy['policyDocument']['Statement'][0]['Effect'] != 'Allow':
                return {'Status': 403, 'Body': {'message': 'User is not authorized to access this resource'}}
            context = {'principalId': policy['principalId'], **policy.get('context', {})}
        if config['authorizationType'] == 'COGNITO_USER_POOLS':
            claims = self.tokens.get(headers.get('Authorization', ''))
            if not claims:
                return {'Status': 401, 'Body': {'message': 'Unauthorized'}}
            context = {'claims': claims}
        if config.get('requestValidatorId'):
            schema = api['models'][config['requestModels']['application/json']]
            missing = [name for name in schema['required'] if name not in (body or {})]
            if missing:
                return {'Status': 400, 'Body': {'message': f"Invalid request body: $: required property '{missing[0]}' not found"}}
        integration = config['methodIntegration']
        if integration['type'] == 'AWS_PROXY':
            function = integration['uri'].split('functions/')[1].split('/')[0].split(':')[-1]
            event = {'httpMethod': method, 'path': f'/{path}', 'headers': headers,
                     'stageVariables': api['stages'][stage]['variables'],
                     'requestContext': {'stage': stage, 'authorizer': context}, 'body': json.dumps(body) if body else None}
            result = load_handler(self.functions[function]['code'])(event, None)
            return {'Status': result['statusCode'], 'Body': json.loads(result['body'])}
        if path == lab.ORDERS_PATH:
            return {'Status': integration['responseStatus'],
                    'Body': {'orderId': 'req-1', 'sku': body['sku'], 'quantity': body['quantity'], 'status': 'ACCEPTED'}}
        return {'Status': integration['responseStatus'],
                'Body': {'sub': context['claims']['sub'], 'email': context['claims']['email']}}


class RestApiDeveloperLabTests(SimpleTestCase):
    def setUp(self):
        cache.clear()
        self.fake = FakeAws()
        for target, replacement in (('_client', lambda name: self.fake), ('_call', self.fake.call)):
            patcher = patch(f'dashboard.labs.apigateway_developer_labs.{target}', side_effect=replacement)
            patcher.start()
            self.addCleanup(patcher.stop)
        sleeper = patch('dashboard.labs.apigateway_developer_labs.time.sleep')
        sleeper.start()
        self.addCleanup(sleeper.stop)
        self.addCleanup(cache.clear)

    def run_all(self):
        return {step: run_lab_step(SERVICE, LAB, step) for step in lab.STEP_KEYS}

    def failed(self, results):
        return {key: result['verification']['message'] for key, result in results.items() if not result['verified']}

    def api(self):
        return self.fake.apis[lab._api_id()]

    def method(self, path, http_method):
        resource = next(item for item in self.api()['resources'].values() if item['path'] == f'/{path}')
        return resource['methods'][http_method]

    def test_lab_is_registered_with_seven_steps_and_exam_tags(self):
        item = next(entry for entry in labs_for_service(SERVICE) if entry['key'] == LAB)
        self.assertEqual(len(item['steps']), 7)
        tasks = {(tag['exam'], tag['task']) for tag in LAB_EXAM_TAGS[(SERVICE, LAB)]}
        self.assertIn(('DVA-C02', '2.1'), tasks)
        self.assertIn(('DVA-C02', '3.3'), tasks)
        primary = [tag for tag in LAB_EXAM_TAGS[(SERVICE, LAB)] if tag['exam'] == 'DVA-C02' and tag['primary']]
        self.assertEqual(primary[0]['task'], '2.1')

    def test_every_step_says_how_floci_emulates_it(self):
        for step in lab.LAB['steps']:
            self.assertIn('How Floci emulates this', step['explanation'], step['key'])

    def test_generated_handlers_behave(self):
        backend = load_handler(lab._zip('orders.py', lab.BACKEND_SOURCE))
        body = json.loads(backend(lab.TEST_EVENT, None)['body'])
        self.assertEqual((body['env'], body['tenant']), ('dev', lab.TENANT))
        authorizer = load_handler(lab._zip('authorizer.py', lab.AUTHORIZER_SOURCE))
        event = {'methodArn': 'arn:aws:execute-api:us-east-1:000000000000:api/dev/GET/orders'}
        allowed = authorizer({**event, 'authorizationToken': lab.ALLOW_TOKEN}, None)
        self.assertEqual(allowed['policyDocument']['Statement'][0]['Resource'], 'arn:aws:execute-api:us-east-1:000000000000:api/dev/*')
        self.assertEqual(allowed['context'], {'tenant': lab.TENANT})
        self.assertEqual(authorizer({**event, 'authorizationToken': lab.DENY_TOKEN}, None)['policyDocument']['Statement'][0]['Effect'], 'Deny')
        with self.assertRaises(Exception):
            authorizer({**event, 'authorizationToken': lab.BAD_TOKEN}, None)

    def test_every_step_verifies_and_status_is_complete(self):
        results = self.run_all()
        self.assertEqual(self.failed(results), {})
        status = lab_status(SERVICE, LAB)
        self.assertTrue(status['complete'])
        self.assertEqual(status['passed_steps'], 7)

    def test_messages_report_what_happened_and_what_floci_skips(self):
        results = self.run_all()
        self.assertIn('tenant acme', results['lambda-authorizer']['verification']['message'])
        self.assertIn("required property 'quantity'", results['request-validation']['verification']['message'])
        self.assertIn('latest configuration on every stage', results['prod-stage']['verification']['message'])
        message = results['api-key-usage-plan']['verification']['message']
        self.assertIn('got 403 on dev', message)
        self.assertIn('does not enforce throttling or quotas', message)
        self.assertIn('checked the plan it sent', message)
        self.assertEqual(results['api-key-usage-plan']['json']['Calls']['WithKey'], [201] * 7)

    def test_an_enforced_quota_and_stored_plan_are_reported_as_on_aws(self):
        self.fake.keep_plan_settings = True
        self.fake.enforce_quota = True
        results = self.run_all()
        self.assertEqual(self.failed(results), {})
        message = results['api-key-usage-plan']['verification']['message']
        self.assertIn('got 429, as on AWS', message)
        self.assertNotIn('checked the plan it sent', message)

    def test_authorizer_wiring_is_checked(self):
        self.run_all()
        self.method(lab.ORDERS_PATH, 'GET')['authorizationType'] = 'NONE'
        self.assertIn(f'must use {lab.TOKEN_AUTHORIZER}', lab._check_lambda_authorizer()[1])
        self.assertFalse(lab_status(SERVICE, LAB)['steps']['lambda-authorizer']['verified'])
        self.assertTrue(run_lab_step(SERVICE, LAB, 'lambda-authorizer')['verified'])

    def test_validator_and_cognito_wiring_are_checked(self):
        self.run_all()
        self.method(lab.ORDERS_PATH, 'POST')['requestModels'] = {}
        self.assertIn(f'against {lab.MODEL}', lab._check_validation()[1])
        self.method(lab.PROFILE_PATH, 'GET')['authorizationType'] = 'NONE'
        self.assertIn(f'must use {lab.COGNITO_AUTHORIZER}', lab._check_cognito()[1])

    def test_prod_needs_its_own_variables(self):
        self.run_all()
        self.api()['stages'][lab.PROD]['variables'] = dict(lab.STAGE_VARIABLES[lab.DEV])
        self.assertIn('must exist with the variables', lab._check_prod_stage()[1])
        self.assertTrue(run_lab_step(SERVICE, LAB, 'prod-stage')['verified'])

    def test_usage_plan_must_cover_prod_and_hold_the_key(self):
        self.run_all()
        plan = next(iter(self.fake.plans.values()))
        plan['keys'].clear()
        self.assertIn(f'must include {lab.API_KEY}', lab._check_api_key()[1])
        self.assertTrue(run_lab_step(SERVICE, LAB, 'api-key-usage-plan')['verified'])

    def test_a_key_without_a_plan_for_prod_fails_the_step(self):
        for step in lab.STEP_KEYS[:-1]:
            run_lab_step(SERVICE, LAB, step)
        original = self.fake.create_usage_plan
        self.fake.create_usage_plan = lambda **kwargs: original(**{**kwargs, 'apiStages': []})
        result = run_lab_step(SERVICE, LAB, 'api-key-usage-plan')
        self.assertFalse(result['verified'])
        self.assertIn('accept it with the key (201)', result['verification']['message'])

    def test_rerunning_steps_reuses_resources_and_validation_drops_the_key_requirement(self):
        self.run_all()
        result = run_lab_step(SERVICE, LAB, 'request-validation')
        self.assertTrue(result['verified'])
        self.assertFalse(self.method(lab.ORDERS_PATH, 'POST')['apiKeyRequired'])
        self.assertFalse(lab_status(SERVICE, LAB)['steps']['api-key-usage-plan']['verified'])
        results = self.run_all()
        self.assertEqual(self.failed(results), {})
        self.assertEqual((len(self.fake.apis), len(self.fake.pools), len(self.fake.keys), len(self.fake.plans)), (1, 1, 1, 1))
        self.assertEqual(len(self.api()['authorizers']), 2)
        self.assertEqual(len(self.api()['validators']), 1)

    def test_an_updatable_usage_plan_is_kept(self):
        self.fake.reject_plan_patch = False
        self.run_all()
