def client_error(code: str, message: str = 'refused') -> ClientError:
    return ClientError({'Error': {'Code': code, 'Message': message}, 'ResponseMetadata': {'HTTPStatusCode': 400}}, 'Operation')


class Body:
    def __init__(self, data: bytes):
        self.data = data

    def read(self):
        return self.data


def run_release(code: bytes, quantity: int) -> dict:
    """Run the handler in a source or artifact zip without importing it."""
    with zipfile.ZipFile(io.BytesIO(code)) as archive:
        source = archive.read('app.py').decode()
    namespace: dict = {}
    exec(compile(source, 'app.py', 'exec'), namespace)  # noqa: S102 - code generated by the lab under test
    return namespace['handler']({'quantity': quantity}, None)


class FakeAws:
    def __init__(self, logs_have_events=False, canary_visible=True, artifact_on_aws_path=False):
        self.logs_have_events = logs_have_events
        self.canary_visible = canary_visible
        self.artifact_on_aws_path = artifact_on_aws_path
        self.ids = itertools.count(1)
        self.buckets: dict[str, dict] = {}
        self.roles: dict[str, dict] = {}
        self.role_policies: dict[tuple[str, str], str] = {}
        self.attached: set[tuple[str, str]] = set()
        self.projects: dict[str, dict] = {}
        self.builds: dict[str, dict] = {}
        self.build_numbers = itertools.count(1)
        self.functions: dict[str, dict] = {}
        self.pipelines: dict[str, dict] = {}
        self.executions: dict[str, dict] = {}
        self.applications: set[str] = set()
        self.groups: dict[tuple[str, str], dict] = {}
        self.deployments: dict[str, dict] = {}
        self.alarms: dict[str, dict] = {}

    # S3
    def create_bucket(self, Bucket):
        if Bucket in self.buckets:
            raise client_error('BucketAlreadyOwnedByYou')
        self.buckets[Bucket] = {'versioning': None, 'objects': {}, 'versions': []}

    def _bucket(self, name):
        if name not in self.buckets:
            raise client_error('NoSuchBucket')
        return self.buckets[name]

    def put_bucket_versioning(self, Bucket, VersioningConfiguration):
        self._bucket(Bucket)['versioning'] = VersioningConfiguration['Status']

    def get_bucket_versioning(self, Bucket):
        status = self._bucket(Bucket)['versioning']
        return {'Status': status} if status else {}

    def put_object(self, Bucket, Key, Body, ContentType=None):
        bucket = self._bucket(Bucket)
        version = f'v{next(self.ids)}'
        bucket['objects'][Key] = Body
        for item in bucket['versions']:
            if item['Key'] == Key:
                item['IsLatest'] = False
        bucket['versions'].append({'Key': Key, 'VersionId': version, 'IsLatest': True, 'LastModified': 'now'})
        return {'VersionId': version}

    def head_object(self, Bucket, Key):
        if Key not in self._bucket(Bucket)['objects']:
            raise client_error('404')
        return {}

    def get_object(self, Bucket, Key):
        objects = self._bucket(Bucket)['objects']
        if Key not in objects:
            raise client_error('NoSuchKey')
        return {'Body': Body(objects[Key])}

    def list_object_versions(self, Bucket, Prefix=''):
        versions = [item for item in self._bucket(Bucket)['versions'] if item['Key'].startswith(Prefix)]
        return {'Versions': versions, 'DeleteMarkers': []}

    def delete_objects(self, Bucket, Delete):
        bucket = self._bucket(Bucket)
        bucket['objects'].clear()
        bucket['versions'].clear()

    def delete_bucket(self, Bucket):
        if self.buckets.pop(Bucket, None) is None:
            raise client_error('NoSuchBucket')

    # IAM
    def get_role(self, RoleName):
        if RoleName not in self.roles:
            raise client_error('NoSuchEntity')
        return {'Role': self.roles[RoleName]}

    def create_role(self, RoleName, AssumeRolePolicyDocument, Description):
        self.roles[RoleName] = {'RoleName': RoleName, 'Arn': f'arn:aws:iam::000000000000:role/{RoleName}'}

    def put_role_policy(self, RoleName, PolicyName, PolicyDocument):
        self.role_policies[(RoleName, PolicyName)] = PolicyDocument

    def get_role_policy(self, RoleName, PolicyName):
        if (RoleName, PolicyName) not in self.role_policies:
            raise client_error('NoSuchEntity')
        return {'PolicyDocument': self.role_policies[(RoleName, PolicyName)]}

    def delete_role_policy(self, RoleName, PolicyName):
        if self.role_policies.pop((RoleName, PolicyName), None) is None:
            raise client_error('NoSuchEntity')

    def attach_role_policy(self, RoleName, PolicyArn):
        self.attached.add((RoleName, PolicyArn))

    def detach_role_policy(self, RoleName, PolicyArn):
        if (RoleName, PolicyArn) not in self.attached:
            raise client_error('NoSuchEntity')
        self.attached.discard((RoleName, PolicyArn))

    def delete_role(self, RoleName):
        if self.roles.pop(RoleName, None) is None:
            raise client_error('NoSuchEntity')

    # CodeBuild
    def create_project(self, name, description, tags, **settings):
        self.projects[name] = {'name': name, **settings}

    def update_project(self, name, **settings):
        self.projects[name].update(settings)

    def batch_get_projects(self, names):
        return {'projects': [self.projects[name] for name in names if name in self.projects]}

    def delete_project(self, name):
        if self.projects.pop(name, None) is None:
            raise client_error('ResourceNotFoundException')

    def start_build(self, projectName):
        project = self.projects[projectName]
        number = next(self.build_numbers)
        build_id = f'{projectName}:{number}'
        bucket, key = project['source']['location'].split('/', 1)
        source = self.buckets[bucket]['objects'][key]
        release = lab._release_in_zip(source)
        phases = [{'phaseType': phase, 'phaseStatus': 'SUCCEEDED'} for phase in
                  ('SUBMITTED', 'QUEUED', 'PROVISIONING', 'DOWNLOAD_SOURCE', 'INSTALL')]
        if release and release.endswith('-broken'):
            phases.append({'phaseType': 'PRE_BUILD', 'phaseStatus': 'FAILED', 'contexts': [{
                'statusCode': 'COMMAND_EXECUTION_ERROR',
                'message': 'Exit code 1: FAIL: test_bulk_order (test_app.PriceTests.test_bulk_order)\n'
                           'AssertionError: 0.0 != 90.0'}]})
            phases += [{'phaseType': 'BUILD', 'phaseStatus': 'SUCCEEDED'},
                       {'phaseType': 'COMPLETED', 'phaseStatus': 'FAILED'}]
            status = 'FAILED'
        else:
            phases += [{'phaseType': phase, 'phaseStatus': 'SUCCEEDED'} for phase in
                       ('PRE_BUILD', 'BUILD', 'POST_BUILD', 'UPLOAD_ARTIFACTS', 'FINALIZING', 'COMPLETED')]
            status = 'SUCCEEDED'
            with zipfile.ZipFile(io.BytesIO(source)) as archive:
                app = archive.read('app.py')
            buffer = io.BytesIO()
            with zipfile.ZipFile(buffer, 'w') as archive:
                archive.writestr('app.py', app)
                archive.writestr('build-info.json', json.dumps({'build': build_id, 'stage': 'ci', 'app': 'quote-service'}))
            artifact_key = (f'{lab.ARTIFACT_PATH}/{number}/{lab.ARTIFACT_NAME}' if self.artifact_on_aws_path
                            else f'{projectName}-{number}.zip')
            self.buckets[project['artifacts']['location']]['objects'][artifact_key] = buffer.getvalue()
        self.builds[build_id] = {'id': build_id, 'buildNumber': number, 'projectName': projectName, 'buildStatus': status,
                                 'phases': phases, 'logs': {'groupName': f'/aws/codebuild/{projectName}',
                                                            'streamName': f'stream/{number}'}}
        return {'build': {'id': build_id, 'buildStatus': 'IN_PROGRESS'}}

    def batch_get_builds(self, ids):
        return {'builds': [self.builds[build_id] for build_id in ids if build_id in self.builds]}

    def list_builds_for_project(self, projectName):
        if projectName not in self.projects:
            raise client_error('ResourceNotFoundException')
        builds = [build for build in self.builds.values() if build['projectName'] == projectName]
        return {'ids': [build['id'] for build in sorted(builds, key=lambda item: -item['buildNumber'])]}

    # Logs
    def get_log_events(self, logGroupName, logStreamName, limit):
        if not self.logs_have_events:
            return {'events': []}
        number = int(logStreamName.rsplit('/', 1)[-1])
        build = next(build for build in self.builds.values() if build['buildNumber'] == number)
        if build['buildStatus'] == 'FAILED':
            return {'events': [{'message': 'FAIL: test_bulk_order'}]}
        return {'events': [{'message': 'OK'}]}

    # Lambda
    def _function(self, name):
        if name not in self.functions:
            raise client_error('ResourceNotFoundException')
        return self.functions[name]

    def create_function(self, FunctionName, Runtime, Handler, Role, Code, Timeout, Description, Publish, Tags):
        code = self.buckets[Code['S3Bucket']]['objects'][Code['S3Key']]
        self.functions[FunctionName] = {'config': {'FunctionName': FunctionName, 'Runtime': Runtime, 'Handler': Handler,
                                                   'Role': Role, 'State': 'Active', 'LastUpdateStatus': 'Successful'},
                                        'latest': code, 'versions': {}, 'aliases': {}}
        if Publish:
            self.publish_version(FunctionName, 'Release 1')

    def get_function(self, FunctionName):
        return {'Configuration': dict(self._function(FunctionName)['config'])}

    def update_function_code(self, FunctionName, S3Bucket, S3Key):
        self._function(FunctionName)['latest'] = self.buckets[S3Bucket]['objects'][S3Key]

    def publish_version(self, FunctionName, Description):
        function = self._function(FunctionName)
        for number, code in function['versions'].items():
            if code == function['latest']:
                return {'Version': number}
        number = str(len(function['versions']) + 1)
        function['versions'][number] = function['latest']
        return {'Version': number}

    def list_versions_by_function(self, FunctionName):
        function = self._function(FunctionName)
        return {'Versions': [{'Version': '$LATEST'}] + [{'Version': number} for number in function['versions']]}

    def create_alias(self, FunctionName, Name, FunctionVersion, Description):
        aliases = self._function(FunctionName)['aliases']
        if Name in aliases:
            raise client_error('ResourceConflictException')
        aliases[Name] = {'Name': Name, 'FunctionVersion': FunctionVersion}

    def get_alias(self, FunctionName, Name):
        aliases = self._function(FunctionName)['aliases']
        if Name not in aliases:
            raise client_error('ResourceNotFoundException')
        return dict(aliases[Name])

    def delete_alias(self, FunctionName, Name):
        del self._function(FunctionName)['aliases'][Name]

    def invoke(self, FunctionName, Qualifier, Payload):
        function = self._function(FunctionName)
        version = Qualifier
        if Qualifier in function['aliases']:
            version = function['aliases'][Qualifier]['FunctionVersion']
        code = function['versions'][version]
        body = run_release(code, json.loads(Payload)['quantity'])
        return {'Payload': Body(json.dumps(body).encode()), 'ExecutedVersion': version}

    def delete_function(self, FunctionName):
        if self.functions.pop(FunctionName, None) is None:
            raise client_error('ResourceNotFoundException')

    # CodePipeline
    def create_pipeline(self, pipeline, tags):
        self.pipelines[pipeline['name']] = pipeline

    def update_pipeline(self, pipeline):
        self.pipelines[pipeline['name']] = pipeline

    def get_pipeline(self, name):
        if name not in self.pipelines:
            raise client_error('PipelineNotFoundException')
        return {'pipeline': self.pipelines[name]}

    def delete_pipeline(self, name):
        if self.pipelines.pop(name, None) is None:
            raise client_error('PipelineNotFoundException')

    def start_pipeline_execution(self, name):
        pipeline = self.pipelines[name]
        execution_id = f'exec-{next(self.ids)}'
        build_stage = next(stage for stage in pipeline['stages'] if stage['name'] == lab.BUILD_STAGE_NAME)
        build = self.start_build(build_stage['actions'][0]['configuration']['ProjectName'])['build']['id']
        failed = self.builds[build]['buildStatus'] != 'SUCCEEDED'
        self.executions[execution_id] = {'status': 'Failed' if failed else 'InProgress',
                                         'token': None if failed else f'token-{execution_id}'}
        return {'pipelineExecutionId': execution_id}

    def get_pipeline_state(self, name):
        waiting = [execution for execution in self.executions.values() if execution['status'] == 'InProgress']
        action = {'actionName': lab.APPROVAL_ACTION,
                  'latestExecution': {'status': 'InProgress', 'token': waiting[-1]['token']} if waiting else {}}
        return {'stageStates': [{'stageName': lab.APPROVAL_STAGE, 'actionStates': [action]}]}

    def put_approval_result(self, pipelineName, stageName, actionName, token, result):
        execution = next(item for item in self.executions.values() if item['token'] == token)
        execution['status'] = 'Succeeded' if result['status'] == 'Approved' else 'Failed'

    def get_pipeline_execution(self, pipelineName, pipelineExecutionId):
        if pipelineExecutionId not in self.executions:
            raise client_error('PipelineExecutionNotFoundException')
        return {'pipelineExecution': {'status': self.executions[pipelineExecutionId]['status']}}

    # CloudWatch
    def put_metric_alarm(self, AlarmName, **settings):
        self.alarms[AlarmName] = {'AlarmName': AlarmName, 'StateValue': 'INSUFFICIENT_DATA', **settings}

    def describe_alarms(self, AlarmNames):
        return {'MetricAlarms': [self.alarms[name] for name in AlarmNames if name in self.alarms]}

    def delete_alarms(self, AlarmNames):
        for name in AlarmNames:
            self.alarms.pop(name, None)

    # CodeDeploy
    def create_application(self, applicationName, computePlatform, tags):
        if applicationName in self.applications:
            raise client_error('ApplicationAlreadyExistsException')
        self.applications.add(applicationName)

    def delete_application(self, applicationName):
        if applicationName not in self.applications:
            raise client_error('ApplicationDoesNotExistException')
        self.applications.discard(applicationName)

    def create_deployment_group(self, applicationName, deploymentGroupName, **settings):
        self.groups[(applicationName, deploymentGroupName)] = {'deploymentGroupName': deploymentGroupName, **settings}

    def update_deployment_group(self, applicationName, currentDeploymentGroupName, **settings):
        self.groups[(applicationName, currentDeploymentGroupName)].update(settings)

    def get_deployment_group(self, applicationName, deploymentGroupName):
        if applicationName not in self.applications:
            raise client_error('ApplicationDoesNotExistException')
        if (applicationName, deploymentGroupName) not in self.groups:
            raise client_error('DeploymentGroupDoesNotExistException')
        return {'deploymentGroupInfo': self.groups[(applicationName, deploymentGroupName)]}

    def delete_deployment_group(self, applicationName, deploymentGroupName):
        if self.groups.pop((applicationName, deploymentGroupName), None) is None:
            raise client_error('DeploymentGroupDoesNotExistException')

    def create_deployment(self, applicationName, deploymentGroupName, description, revision, deploymentConfigName=None):
        spec = json.loads(revision['appSpecContent']['content'])
        properties = next(iter(spec['Resources'][0].values()))['Properties']
        config = deploymentConfigName or self.groups[(applicationName, deploymentGroupName)]['deploymentConfigName']
        deployment_id = f'd-{next(self.ids)}'
        self.deployments[deployment_id] = {'status': 'InProgress', 'polls': 0, 'config': config, 'props': properties}
        return {'deploymentId': deployment_id}

    def get_deployment(self, deploymentId):
        if deploymentId not in self.deployments:
            raise client_error('DeploymentDoesNotExistException')
        deployment = self.deployments[deploymentId]
        props = deployment['props']
        alias = self.functions[props['Name']]['aliases'][props['Alias']]
        if deployment['status'] == 'InProgress':
            canary = 'Canary' in deployment['config'] and deployment['polls'] == 0 and self.canary_visible
            if canary:
                alias['RoutingConfig'] = {'AdditionalVersionWeights': {props['TargetVersion']: 0.1}}
            else:
                alias['FunctionVersion'] = props['TargetVersion']
                alias.pop('RoutingConfig', None)
                deployment['status'] = 'Succeeded'
            deployment['polls'] += 1
        return {'deploymentInfo': {'status': deployment['status']}}


class LambdaCicdLabTests(SimpleTestCase):
    def setUp(self):
        cache.clear()
        self.fake = FakeAws()
        patcher = patch('dashboard.labs.codepipeline_labs._client', side_effect=lambda name: self.fake)
        patcher.start()
        self.addCleanup(patcher.stop)
        sleeper = patch('dashboard.labs.codepipeline_labs.time.sleep')
        sleeper.start()
        self.addCleanup(sleeper.stop)
        self.addCleanup(cache.clear)

    def run_all(self):
        return {step: run_lab_step(SERVICE, LAB, step) for step in lab.STEP_KEYS}

    def failed(self):
        return [step for step, item in lab_status(SERVICE, LAB)['steps'].items() if not item['verified']]

    def test_lab_is_registered_with_nine_steps_exam_tags_and_a_batch(self):
        item = next(entry for entry in labs_for_service(SERVICE) if entry['key'] == LAB)
        self.assertEqual(len(item['steps']), 9)
        tasks = {(tag['exam'], tag['task']) for tag in LAB_EXAM_TAGS[(SERVICE, LAB)]}
        self.assertIn(('DVA-C02', '3.4'), tasks)
        self.assertIn(('DVA-C02', '4.1'), tasks)
        primary = [tag for tag in LAB_EXAM_TAGS[(SERVICE, LAB)] if tag['exam'] == 'DVA-C02' and tag['primary']]
        self.assertEqual(primary[0]['task'], '3.4')
        self.assertIn(SERVICE, [batch['service'] for batch in LAB_BATCH_ORDER])

    def test_every_step_says_how_floci_emulates_it(self):
        for step in lab.LAB['steps']:
            self.assertIn('How Floci emulates this', step['explanation'], step['key'])

    def test_generated_sources_pass_and_fail_their_own_tests(self):
        for release, broken, passes in (('1', False, True), ('2', False, True), ('2', True, False)):
            with self.subTest(release=release, broken=broken):
                archive = zipfile.ZipFile(io.BytesIO(lab.source_zip(release, broken)))
                namespace: dict = {}
                exec(compile(archive.read('app.py').decode(), 'app.py', 'exec'), namespace)  # noqa: S102
                expected = lab.RELEASES[release][1]
                self.assertEqual(namespace['price'](lab.BULK_QUANTITY) == expected, passes)
                self.assertIn(f'app.price({lab.BULK_QUANTITY}), {expected!r}', archive.read('test_app.py').decode())
                self.assertEqual(lab._release_in_zip(lab.source_zip(release, broken)), release + ('-broken' if broken else ''))
        self.assertEqual(lab.bulk_total(0.1), 90.0)
        self.assertNotIn('{{', lab.BUILDSPEC)

    def test_every_step_verifies_and_status_is_complete(self):
        results = self.run_all()
        failed = {key: result['verification']['message'] for key, result in results.items() if not result['verified']}
        self.assertEqual(failed, {})
        status = lab_status(SERVICE, LAB)
        self.assertTrue(status['complete'])
        self.assertEqual(status['passed_steps'], 9)

    def test_messages_report_what_happened_and_what_floci_skips(self):
        results = self.run_all()
        self.assertIn('does not check the role', results['build-project']['verification']['message'])
        self.assertIn('AWS would write builds/<build-id>/quote-service.zip', results['first-build']['verification']['message'])
        self.assertEqual(results['first-build']['json']['BuildInfo']['stage'], 'ci')
        failing = results['failing-build']['verification']['message']
        self.assertIn('failed in PRE_BUILD', failing)
        self.assertIn('expected 90.0', failing)
        self.assertIn('log empty', failing)
        self.assertIn('holding 10% on version 2', results['canary-deploy']['verification']['message'])
        self.assertIn('seconds instead of 5 minutes', results['canary-deploy']['verification']['message'])
        self.assertEqual(results['canary-deploy']['json']['LiveInvoke']['Response']['total'], 90.0)
        self.assertEqual(results['rollback']['json']['LiveInvoke']['Response']['release'], '1')

    def test_build_logs_and_aws_artifact_paths_need_no_fallback(self):
        self.fake.logs_have_events = True
        self.fake.artifact_on_aws_path = True
        results = self.run_all()
        self.assertTrue(all(result['verified'] for result in results.values()))
        self.assertNotIn('AWS would write', results['first-build']['verification']['message'])
        self.assertNotIn('log empty', results['failing-build']['verification']['message'])

    def test_a_canary_too_fast_to_sample_still_passes_and_says_so(self):
        self.fake.canary_visible = False
        results = self.run_all()
        self.assertTrue(results['canary-deploy']['verified'])
        self.assertIn('finished before the step could sample', results['canary-deploy']['verification']['message'])

    def test_project_settings_are_checked(self):
        self.run_all()
        project = self.fake.projects[lab.PROJECT]
        project['environment']['environmentVariables'] = []
        self.assertIn('STAGE=ci', lab._check_project()[1])
        project['environment']['environmentVariables'] = [{'name': 'STAGE', 'value': 'ci'}]
        self.fake.role_policies[(lab.BUILD_ROLE, lab.INLINE_POLICY)] = json.dumps({'Statement': []})
        self.assertIn('write build logs', lab._check_project()[1])
        self.assertEqual(self.failed()[0], 'build-project')
        self.assertTrue(run_lab_step(SERVICE, LAB, 'build-project')['verified'])

    def test_pipeline_structure_is_checked(self):
        self.run_all()
        pipeline = self.fake.pipelines[lab.PIPELINE]
        pipeline['stages'] = pipeline['stages'][:2]
        self.assertIn('in order', lab._check_pipeline()[1])
        self.assertIn('pipeline', self.failed())
        self.assertTrue(run_lab_step(SERVICE, LAB, 'pipeline')['verified'])

    def test_broken_source_fails_the_pipeline_check_and_the_release(self):
        for step in lab.STEP_KEYS[:6]:
            run_lab_step(SERVICE, LAB, step)
        self.fake.put_object(Bucket=lab.BUCKET, Key=lab.SOURCE_KEY, Body=lab.source_zip('2', broken=True))
        self.assertIn('fixed release 2', lab._check_pipeline()[1])
        result = run_lab_step(SERVICE, LAB, 'approve-release')
        self.assertFalse(result['verified'])

    def test_rollback_needs_all_traffic_on_version_one(self):
        self.run_all()
        alias = self.fake.functions[lab.FUNCTION]['aliases'][lab.ALIAS]
        alias['RoutingConfig'] = {'AdditionalVersionWeights': {'2': 0.1}}
        self.assertIn('all traffic to version 1', lab._check_rollback()[1])
        alias.pop('RoutingConfig')
        self.assertTrue(lab._check_rollback()[0])

    def test_rerunning_steps_reuses_resources(self):
        self.run_all()
        results = self.run_all()
        failed = {key: result['verification']['message'] for key, result in results.items() if not result['verified']}
        self.assertEqual(failed, {})
        self.assertEqual(len(self.fake.projects), 1)
        self.assertEqual(len(self.fake.pipelines), 1)
        # Each pipeline build packages a new build-info.json, so the second canary publishes version 3.
        self.assertEqual(sorted(self.fake.functions[lab.FUNCTION]['versions']), ['1', '2', '3'])
        self.assertEqual(len(self.fake.groups), 1)

    def test_steps_out_of_order_explain_what_is_missing(self):
        for step in lab.STEP_KEYS[1:]:
            with self.subTest(step=step):
                self.assertIn('first', run_lab_step(SERVICE, LAB, step)['verification']['message'])

    def test_reset_removes_everything_and_clears_progress(self):
        self.run_all()
        result = reset_lab(SERVICE, LAB)
        self.assertEqual(result['errors'], [])
        for store in (self.fake.buckets, self.fake.roles, self.fake.role_policies, self.fake.attached, self.fake.projects,
                      self.fake.functions, self.fake.pipelines, self.fake.applications, self.fake.groups, self.fake.alarms):
            self.assertFalse(store)
        self.assertEqual(lab_status(SERVICE, LAB)['passed_steps'], 0)

    def test_reset_with_nothing_to_delete_is_clean(self):
        result = reset_lab(SERVICE, LAB)
        self.assertEqual(result['errors'], [])
        self.assertEqual(result['deleted_resources'], [])
